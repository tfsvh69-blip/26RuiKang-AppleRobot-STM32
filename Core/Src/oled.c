static const OLED_Glyph8x16 *OLED_FindGlyph(char ch)
{
  uint32_t i;
  for (i = 0; i < (sizeof(oled_font_8x16) / sizeof(oled_font_8x16[0])); i++)
  {
    if (oled_font_8x16[i].ch == ch)
      return &oled_font_8x16[i];
  }
  return &oled_font_8x16[0];
}

