HAL_StatusTypeDef OLED_Init(void)
{
  /* 典型SSD1306初始化序列（参考你提供的示例） */
  static const uint8_t init_cmds[] = {
    0xAE,       /* display off */
    0xD5, 0x80, /* clock divide */
    0xA8, 0x3F, /* multiplex */
    0xD3, 0x00, /* display offset */
    0x40,       /* start line */
    0xA1,       /* segment remap */
    0xC8,       /* COM scan dir */
    0xDA, 0x12, /* COM pins */
    0x81, 0xCF, /* contrast */
    0xD9, 0xF1, /* pre-charge */
    0xDB, 0x30, /* vcomh */
    0xA4,       /* output follows RAM */
    0xA6,       /* normal display */
    0x8D, 0x14, /* charge pump */
    0xAF        /* display on */
  };

  OLED_WaitI2CReady(100);

  /* 先探测器件是否应答，避免后续DMA一直busy导致任务卡住 */
  oled_i2c_addr = (uint16_t)OLED_I2C_ADDR;
  if (HAL_I2C_IsDeviceReady(&hi2c1, oled_i2c_addr, 2, 100) != HAL_OK)
  {
    /* 兼容部分模块使用0x3D地址 */
    oled_i2c_addr = (uint16_t)(0x3Du << 1);
    if (HAL_I2C_IsDeviceReady(&hi2c1, oled_i2c_addr, 2, 100) != HAL_OK)
      return HAL_ERROR;
  }

  if (OLED_WriteCommands(init_cmds, (uint16_t)sizeof(init_cmds)) != HAL_OK)
    return HAL_ERROR;

  OLED_BufferClear();
  return OLED_Update();
}

HAL_StatusTypeDef OLED_Clear(void)
{
  OLED_BufferClear();
  return OLED_Update();
}

HAL_StatusTypeDef OLED_ClearBuffer(void)
{
  OLED_BufferClear();
  return HAL_OK;
}

HAL_StatusTypeDef OLED_Flush(void)
{
  return OLED_Update();
}

HAL_StatusTypeDef OLED_Update(void)
{
  HAL_StatusTypeDef st;
  uint8_t page;

  for (page = 0; page < (OLED_HEIGHT / 8u); page++)
  {
    uint8_t set_pos[] = {
      (uint8_t)(0xB0u | page), /* page */
      0x10u,                   /* high column = 0 */
      0x00u                    /* low column = 0 */
    };

    st = OLED_WriteCommands(set_pos, (uint16_t)sizeof(set_pos));
    if (st != HAL_OK)
      return st;

    st = OLED_WriteData(&oled_buffer[OLED_WIDTH * page], OLED_WIDTH);
    if (st != HAL_OK)
      return st;
  }

  return HAL_OK;
}

HAL_StatusTypeDef OLED_DrawString(uint8_t line, uint8_t column, const char *str)
{
  uint8_t x;
  uint8_t y;
  uint32_t i;

  if (str == NULL)
    return HAL_ERROR;
  if (line < 1 || line > OLED_TEXT_LINES)
    return HAL_ERROR;
  if (column < 1 || column > OLED_TEXT_COLUMNS)
    return HAL_ERROR;

  x = (uint8_t)((column - 1u) * 8u);
  y = (uint8_t)((line - 1u) * 16u);

  for (i = 0; str[i] != '\0'; i++)
  {
    if ((uint32_t)(x + 8u) > OLED_WIDTH)
      break;

    OLED_DrawChar8x16(x, y, str[i]);
    x = (uint8_t)(x + 8u);
  }

  return HAL_OK;
}

HAL_StatusTypeDef OLED_ShowString(uint8_t line, uint8_t column, const char *str)
{
  HAL_StatusTypeDef st;
  st = OLED_DrawString(line, column, str);
  if (st != HAL_OK)
    return st;
  return OLED_Update();
}

HAL_StatusTypeDef OLED_DrawNum(uint8_t line, uint8_t column, uint32_t num, uint8_t len)
{
  char buf[11];
  int8_t i;

  if (len < 1 || len > 10)
    return HAL_ERROR;

  for (i = (int8_t)len - 1; i >= 0; i--)
  {
    buf[i] = (char)('0' + (num % 10u));
    num /= 10u;
  }
  buf[len] = '\0';

  /* 左侧空格填充：当高位为0且非最后一位时显示空格 */
  for (i = 0; i < (int8_t)len - 1; i++)
  {
    if (buf[i] == '0')
      buf[i] = ' ';
    else
      break;
  }

  return OLED_DrawString(line, column, buf);
}

HAL_StatusTypeDef OLED_ShowNum(uint8_t line, uint8_t column, uint32_t num, uint8_t len)
{
  HAL_StatusTypeDef st;
  st = OLED_DrawNum(line, column, num, len);
  if (st != HAL_OK)
    return st;
  return OLED_Update();
}

