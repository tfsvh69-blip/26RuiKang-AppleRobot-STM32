static HAL_StatusTypeDef OLED_WriteCommands(const uint8_t *cmds, uint16_t len)
{
  HAL_StatusTypeDef st;
  uint16_t i;

  if (cmds == NULL || len == 0)
    return HAL_ERROR;

  /* init/cursor命令都很短，限制len <= 32 */
  if (len > 32u)
    return HAL_ERROR;

  oled_tx_cmd_buf[0] = 0x00u; /* control byte: commands */
  for (i = 0; i < len; i++)
    oled_tx_cmd_buf[1u + i] = cmds[i];

  OLED_WaitI2CReady(100);
  st = HAL_I2C_Master_Transmit_DMA(&hi2c1, oled_i2c_addr, oled_tx_cmd_buf, (uint16_t)(1u + len));
  if (st != HAL_OK)
    return st;

  OLED_WaitI2CReady(100);
  if (HAL_I2C_GetState(&hi2c1) != HAL_I2C_STATE_READY)
    return HAL_TIMEOUT;
  return HAL_OK;
}

static HAL_StatusTypeDef OLED_WriteData(const uint8_t *data, uint16_t len)
{
  HAL_StatusTypeDef st;
  uint16_t i;

  if (data == NULL || len == 0)
    return HAL_ERROR;

  /* 本驱动按page写，期望len == 128 */
  if (len > OLED_WIDTH)
    return HAL_ERROR;

  oled_tx_data_buf[0] = 0x40u; /* control byte: data */
  for (i = 0; i < len; i++)
    oled_tx_data_buf[1u + i] = data[i];

  OLED_WaitI2CReady(100);
  st = HAL_I2C_Master_Transmit_DMA(&hi2c1, oled_i2c_addr, oled_tx_data_buf, (uint16_t)(1u + len));
  if (st != HAL_OK)
    return st;

  OLED_WaitI2CReady(100);
  if (HAL_I2C_GetState(&hi2c1) != HAL_I2C_STATE_READY)
    return HAL_TIMEOUT;
  return HAL_OK;
}

static void OLED_WaitI2CReady(uint32_t timeout_ms)
{
  uint32_t start = HAL_GetTick();

  while (HAL_I2C_GetState(&hi2c1) != HAL_I2C_STATE_READY)
  {
    if ((HAL_GetTick() - start) > timeout_ms)
      break;

    /* RTOS运行时避免HAL_Delay忙等占CPU */
    if (osKernelGetState() == osKernelRunning)
      osDelay(1);
    else
      HAL_Delay(1);
  }
}

static void OLED_BufferClear(void)
{
  uint32_t i;
  for (i = 0; i < sizeof(oled_buffer); i++)
    oled_buffer[i] = 0x00u;
}

static void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t on)
{
  uint16_t index;
  uint8_t mask;

  if (x >= OLED_WIDTH || y >= OLED_HEIGHT)
    return;

  index = (uint16_t)(x + (uint16_t)(y / 8u) * OLED_WIDTH);
  mask = (uint8_t)(1u << (y % 8u));

  if (on)
    oled_buffer[index] |= mask;
  else
    oled_buffer[index] &= (uint8_t)~mask;
}

static void OLED_DrawChar8x16(uint8_t x, uint8_t y, char ch)
{
  const OLED_Glyph8x16 *g;
  uint8_t row;
  uint8_t col;

  if ((uint32_t)x + 8u > OLED_WIDTH || (uint32_t)y + 16u > OLED_HEIGHT)
    return;

  /* 只支持大写字母/数字/空格；小写自动转大写 */
  if (ch >= 'a' && ch <= 'z')
    ch = (char)(ch - 'a' + 'A');

  g = OLED_FindGlyph(ch);

  for (row = 0; row < 16u; row++)
  {
    uint8_t bits = g->rows[row];
    for (col = 0; col < 8u; col++)
    {
      uint8_t on = (uint8_t)((bits & (uint8_t)(0x80u >> col)) ? 1u : 0u);
      OLED_DrawPixel((uint8_t)(x + col), (uint8_t)(y + row), on);
    }
  }
}

